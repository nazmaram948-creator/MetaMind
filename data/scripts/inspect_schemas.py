"""Print the schema of every downloaded data file (and write docs/data_schemas.md).

We never guess column names: run this after the download_* scripts and adapt
the normaliser to what it prints.

For each CSV/TSV/XLSX under data/raw it reports: size, row count, columns with
dtype / null count / example value, and, for long-format files, the distinct
values of the dimension columns (facet, variable, geography, ...).

Usage:  python data/scripts/inspect_schemas.py [path ...]
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

from _common import RAW, ROOT

OUT = ROOT / "docs" / "data_schemas.md"
CHUNK = 500_000
# Columns that look like dimensions in long-format files: list their distinct values.
DIM_HINTS = {
    "facet", "variable", "geography", "geo_level", "category_name", "metric_id",
    "hierarchy_level", "level", "platform_and_product", "date_start", "date_end",
    "scale_id", "task_type", "interaction_type", "domain_source", "recommend_suppress",
    "not_relevant", "category",
}
MAX_DISTINCT = 60
# Spreadsheets with title rows above the real header.
HEADER_ROW = {"ESCO_to_ONET-SOC.xlsx": 3}


def read_excel(path: Path, nrows: int | None = None) -> pd.DataFrame:
    return pd.read_excel(path, nrows=nrows, dtype=str, header=HEADER_ROW.get(path.name, 0))


def read_sample(path: Path, nrows: int | None = 2000) -> pd.DataFrame:
    if path.suffix == ".jsonl":
        return pd.read_json(path, lines=True, nrows=nrows)
    if path.suffix in (".xlsx", ".xls"):
        return read_excel(path, nrows)
    sep = "\t" if path.suffix == ".tsv" else ","
    return pd.read_csv(path, nrows=nrows, sep=sep, low_memory=False)


def describe(path: Path) -> str:
    rel = path.relative_to(ROOT).as_posix()
    size = path.stat().st_size
    lines = [f"## `{rel}`", "", f"- size: {size:,} bytes"]

    sample = read_sample(path)
    dims = [c for c in sample.columns if c.lower().replace(" ", "_") in DIM_HINTS]

    # Full pass (chunked for big files) for row count + distinct values of dims.
    if path.suffix in (".xlsx", ".xls", ".jsonl"):
        full = pd.read_json(path, lines=True) if path.suffix == ".jsonl" else read_excel(path)
        n_rows = len(full)
        distinct = {c: full[c].value_counts(dropna=False) for c in dims}
    else:
        sep = "\t" if path.suffix == ".tsv" else ","
        n_rows = 0
        distinct: dict[str, pd.Series] = {}
        for chunk in pd.read_csv(path, sep=sep, chunksize=CHUNK, low_memory=False,
                                 usecols=dims or None):
            n_rows += len(chunk)
            for c in dims:
                vc = chunk[c].value_counts(dropna=False)
                distinct[c] = vc if c not in distinct else distinct[c].add(vc, fill_value=0)

    lines.append(f"- rows: {n_rows:,}")
    lines.append("")
    lines.append("| column | dtype (sample) | nulls in sample | example |")
    lines.append("|---|---|---|---|")
    for c in sample.columns:
        s = sample[c]
        ex = s.dropna().iloc[0] if s.notna().any() else ""
        ex = str(ex).replace("|", "\\|").replace("\n", " ")
        if len(ex) > 70:
            ex = ex[:67] + "..."
        lines.append(f"| `{c}` | {s.dtype} | {int(s.isna().sum())}/{len(s)} | {ex} |")

    for c, vc in distinct.items():
        vc = vc.sort_values(ascending=False)
        shown = vc.head(MAX_DISTINCT)
        lines.append("")
        more = f" (showing {MAX_DISTINCT})" if len(vc) > MAX_DISTINCT else ""
        lines.append(f"**distinct `{c}`: {len(vc)}{more}** — "
                     + ", ".join(f"`{k}` ({int(v):,})" for k, v in shown.items()))
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    paths = [Path(p).resolve() for p in sys.argv[1:]] or sorted(
        p for p in RAW.rglob("*")
        if p.suffix in (".csv", ".tsv", ".xlsx", ".xls", ".jsonl") and p.is_file()
    )
    parts = ["# Data schemas (generated by data/scripts/inspect_schemas.py)", ""]
    for p in paths:
        print(f"inspecting {p.relative_to(ROOT).as_posix()} ...", file=sys.stderr)
        try:
            parts.append(describe(p))
        except Exception as e:  # report and keep going
            parts.append(f"## `{p.relative_to(ROOT).as_posix()}`\n\nERROR: {e}\n")
    text = "\n".join(parts)
    if not sys.argv[1:]:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT).as_posix()}", file=sys.stderr)
    print(text)


if __name__ == "__main__":
    main()
